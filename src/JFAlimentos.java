    private void BInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BInsertarActionPerformed
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir"));
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File archivo = fc.getSelectedFile();

            try {
                // Lee los bytes del archivo directo desde la memoria
                fotoBytes = java.nio.file.Files.readAllBytes(archivo.toPath());

                // Muestra la vista previa en el JLabel
                cartel = new ImageIcon(archivo.getPath());
                LFoto.setIcon(new ImageIcon(cnx.escalarImagen(cartel.getImage(), 194, 235)));
            } catch (java.io.IOException e) {
                JOptionPane.showMessageDialog(this, "Error al leer la imagen: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_BInsertarActionPerformed

    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistrarActionPerformed
        int id = Integer.parseInt(txtID.getText());
        String nombre = txtNombre.getText();
        String descripcion = txaDescripcion.getText();
        float precio = Float.parseFloat(txtPecio.getText());
        String categoria = cboCategoria.getSelectedItem().toString();
        String estado = cboEstado.getSelectedItem().toString();

        // Se envía fotoBytes (byte[]) en lugar de ImageIcon
        Alimento ali = new Alimento(id, nombre, descripcion, precio, fotoBytes, categoria, estado);

        if (ali.insertar(cnx.con) == 1) {
            cnx.entablar("SELECT * FROM alimentos", TConsultas, 20, 40, 40);
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el alimento");
        }
    }//GEN-LAST:event_BRegistrarActionPerformed

    private void TConsultasMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TConsultasMousePressed
        int ren = TConsultas.getSelectedRow();
        DefaultTableModel modelo = (DefaultTableModel) TConsultas.getModel();

        if (ren >= 0) {
            // Cargar los textos a sus cajas correspondientes según tu formulario
            txtID.setText(modelo.getValueAt(ren, 0).toString());
            txtNombre.setText(modelo.getValueAt(ren, 1).toString());
            txaDescripcion.setText(modelo.getValueAt(ren, 2).toString());
            txtPecio.setText(modelo.getValueAt(ren, 3).toString());
            cboCategoria.setSelectedItem(modelo.getValueAt(ren, 4).toString());
            cboEstado.setSelectedItem(modelo.getValueAt(ren, 5).toString());

            // Obtener la imagen de la columna 6 (Foto)
            Object valorFoto = modelo.getValueAt(ren, 6);

            if (valorFoto instanceof ImageIcon) {
                // Si la tabla devuelve directamente un ImageIcon
                ImageIcon icon = (ImageIcon) valorFoto;
                cartel = new ImageIcon(cnx.escalarImagen(icon.getImage(), 194, 235));
                LFoto.setIcon(cartel);
            } else if (valorFoto instanceof byte[]) {
                // Si la tabla devuelve un byte[]
                byte[] bytes = (byte[]) valorFoto;
                ImageIcon icon = new ImageIcon(bytes);
                cartel = new ImageIcon(cnx.escalarImagen(icon.getImage(), 194, 235));
                LFoto.setIcon(cartel);
            }
        }
    }//GEN-LAST:event_TConsultasMousePressed

