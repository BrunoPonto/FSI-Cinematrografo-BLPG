    private void BAceptarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BAceptarActionPerformed
        String usr = TUsuario.getText();
        String nip = TPassword.getText();

        String sql = String.format(rol, usr, nip);
        String tipo = cnx.obtenerDato(sql);

        switch (tipo) {

            case "mesero":
                JFMesero mes = new JFMesero();
                cnx.desconectar();
                this.dispose();
                mes.setVisible(true);
                break;
            case "cajero":
                JFCajero ca = new JFCajero();
                cnx.desconectar();
                this.dispose();
                ca.setVisible(true);
                break;
            case "cocinero":
                JFCocinero coc = new JFCocinero();
                cnx.desconectar();
                this.dispose();
                coc.setVisible(true);
                break;
            case "gerente":
                JFGerente ge = new JFGerente();
                cnx.desconectar();
                this.dispose();
                ge.setVisible(true);
                break;
            case "":
                JOptionPane.showMessageDialog(this, "Credenciales incorrectas");
                intentos++;

                if (intentos >= 3) {
                    JOptionPane.showMessageDialog(this, "Numero de intentos excedidos");
                    System.exit(0);
                }
                break;

        }
    }//GEN-LAST:event_BAceptarActionPerformed

